num1=int(input("ingrese un valor numerico: "))
num2=int(input("ingrese un 2do valor numerico: "))

if num1 > num2:
    resultado=(num1 - num2)
    print("el resultado de la suma de los valores es: ",resultado)
else:
    resultado=(num1 + num2)
    print("el resultado de la resta de los valores es: ",resultado)